export function searchCatalog(
  query: string,
  catalog: readonly string[],
  recent: readonly string[] = [],
  limit = 8,
): string[] {
  const term = query.trim().toLocaleLowerCase('en');
  const unique = [
    ...new Map(
      [...recent, ...catalog].map((name) => [name.toLocaleLowerCase('en'), name]),
    ).values(),
  ];
  return unique
    .filter((name) => !term || name.toLocaleLowerCase('en').includes(term))
    .sort((a, b) => {
      const startsA = a.toLocaleLowerCase('en').startsWith(term);
      const startsB = b.toLocaleLowerCase('en').startsWith(term);
      return Number(startsB) - Number(startsA);
    })
    .slice(0, Math.max(0, limit));
}
